#!/usr/bin/env node
/**
 * Pull Firebase web SDK config into .env.local (VITE_* vars).
 *
 * Usage:
 *   npm run env:sync
 *   npm run env:sync -- rabbitholeapps
 *   FIREBASE_WEB_APP_ID=1:... npm run env:sync
 *
 * Requires: firebase CLI logged in (`firebase login`)
 * Still fill manually: VITE_MASTER_ADMIN_EMAIL, VITE_RECAPTCHA_SITE_KEY
 */

import { execSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const envPath = join(root, '.env.local')
const project =
  process.argv[2] || process.env.FIREBASE_PROJECT_ID || 'rabbitholeapps'

function run(cmd) {
  return execSync(cmd, { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] })
}

function parseEnv(text) {
  const out = {}
  for (const line of text.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const i = trimmed.indexOf('=')
    if (i === -1) continue
    out[trimmed.slice(0, i)] = trimmed.slice(i + 1)
  }
  return out
}

function listWebAppId() {
  const fromEnv = process.env.FIREBASE_WEB_APP_ID?.trim()
  if (fromEnv) return fromEnv

  const out = run(`firebase apps:list WEB --project ${project}`)
  const match = out.match(
    /│\s+[^│]+\s+│\s+(1:\d+:web:[a-f0-9]+)\s+│/i,
  )
  if (!match) {
    throw new Error(
      `No WEB app in project "${project}". Register one in Firebase Console → Project settings → Your apps.`,
    )
  }
  return match[1]
}

function fetchSdkConfig(appId) {
  const raw = run(
    `firebase apps:sdkconfig WEB ${appId} --project ${project}`,
  )
  const start = raw.indexOf('{')
  const end = raw.lastIndexOf('}')
  if (start === -1 || end === -1) {
    throw new Error('Could not parse firebase apps:sdkconfig output')
  }
  return JSON.parse(raw.slice(start, end + 1))
}

const existing = existsSync(envPath) ? parseEnv(readFileSync(envPath, 'utf8')) : {}

console.log(`Syncing Firebase web config for project: ${project}`)
const appId = listWebAppId()
console.log(`Web app: ${appId}`)

const sdk = fetchSdkConfig(appId)

const lines = [
  '# Generated by npm run env:sync — safe to edit. Not committed to git.',
  `# Project: ${project}`,
  `# App: ${appId}`,
  '',
  `VITE_FIREBASE_API_KEY=${sdk.apiKey}`,
  `VITE_FIREBASE_AUTH_DOMAIN=${sdk.authDomain}`,
  `VITE_FIREBASE_PROJECT_ID=${sdk.projectId}`,
  `VITE_FIREBASE_STORAGE_BUCKET=${sdk.storageBucket}`,
  `VITE_FIREBASE_MESSAGING_SENDER_ID=${sdk.messagingSenderId}`,
  `VITE_FIREBASE_APP_ID=${sdk.appId}`,
  sdk.measurementId
    ? `VITE_FIREBASE_MEASUREMENT_ID=${sdk.measurementId}`
    : '# VITE_FIREBASE_MEASUREMENT_ID=',
  '',
  '# Your Gmail — first sign-in with this address becomes admin.',
  `VITE_MASTER_ADMIN_EMAIL=${existing.VITE_MASTER_ADMIN_EMAIL || ''}`,
  '',
  '# reCAPTCHA v3 site key (Google reCAPTCHA admin + Firebase App Check).',
  `VITE_RECAPTCHA_SITE_KEY=${existing.VITE_RECAPTCHA_SITE_KEY || ''}`,
  '',
  'VITE_USE_EMULATORS=false',
  '# VITE_USE_DEMO=true',
  '',
]

writeFileSync(envPath, `${lines.join('\n')}\n`)
console.log(`Wrote ${envPath}`)

const missing = []
for (const key of ['VITE_MASTER_ADMIN_EMAIL', 'VITE_RECAPTCHA_SITE_KEY']) {
  const line = lines.find((l) => l.startsWith(`${key}=`))
  if (!line?.slice(key.length + 1)) missing.push(key)
}

if (missing.length) {
  console.log('')
  console.log('Still add manually in .env.local:')
  for (const key of missing) console.log(`  - ${key}`)
}
